"""Package the shared Scala.js Canvas game for WebKit or static web hosting."""
from __future__ import annotations

from argparse import Namespace
import hashlib
import json
from pathlib import Path
import shutil
import tempfile

MARKER = ".whaley-web-bundle"
# Keep the ownership token stable for bundles made before the CLI consolidation.
MARKER_CONTENT = "Generated by Scala/tools/package_web.py\n"
CHECKOUT_PLACEHOLDER = ".keep"


def render_template(template: Path) -> str:
    source = template.read_text(encoding="utf-8")
    signature = "@(gameName: String)\n"
    if not source.startswith(signature) or "@gameName" not in source:
        raise RuntimeError("The original Twirl Canvas page contract changed")
    # The static hosts use the same DOM and relative asset URLs as Play.
    return source[len(signature):].replace("@gameName", "Gray Whale")


def has_checkout_placeholder(destination: Path) -> bool:
    placeholder = destination / CHECKOUT_PLACEHOLDER
    return (not placeholder.is_symlink() and placeholder.is_file()
            and placeholder.stat().st_size == 0)


def validate_destination(staged: Path, destination: Path, template: Path, *, root: Path) -> None:
    """Only replace generated output, never an input or an unrelated directory."""
    if destination.is_symlink():
        raise RuntimeError("The bundle destination cannot be a symbolic link")
    staged, destination, template = staged.resolve(), destination.resolve(), template.resolve()
    root = root.resolve()
    if (staged == destination or staged in destination.parents or destination in staged.parents
            or destination == template or destination in template.parents
            or destination == root or destination in root.parents):
        raise RuntimeError("The bundle destination overlaps source files")
    if not destination.exists():
        return
    if not destination.is_dir():
        raise RuntimeError("The bundle destination must be a directory")
    entries = {path.name for path in destination.iterdir()}
    # Xcode's folder reference exists in a checkout because of this empty file.
    if has_checkout_placeholder(destination):
        entries.discard(CHECKOUT_PLACEHOLDER)
    # Opening the folder in Finder must not prevent its first build or upgrade.
    finder_metadata = destination / ".DS_Store"
    if not finder_metadata.is_symlink() and finder_metadata.is_file():
        entries.discard(".DS_Store")
    if not entries:
        return
    marker = destination / MARKER
    if marker.is_file() and marker.read_text(encoding="utf-8") == MARKER_CONTENT:
        return
    # Accept the previous WebKit packager's generated layout once, without
    # requiring users to delete their existing app resources after upgrading.
    legacy_files = ("index.html", "assets/main.js", "assets/styles.css", "assets/provenance.json")
    if entries <= {"index.html", "assets", ".nojekyll"} and all(
            (destination / name).is_file() for name in legacy_files):
        return
    raise RuntimeError("Refusing to replace a nonempty directory that is not a generated Whaley bundle: "
                       + str(destination))


def validate_assets(staged: Path) -> None:
    required = ("main.js", "styles.css", "assets/provenance.json")
    missing = [name for name in required if not (staged / name).is_file()]
    if missing:
        raise RuntimeError("Missing staged Scala.js artifacts: " + ", ".join(missing))
    try:
        manifest = json.loads((staged / "assets/provenance.json").read_text(encoding="utf-8"))
    except (ValueError, UnicodeError) as error:
        raise RuntimeError("Invalid original asset manifest") from error
    if not isinstance(manifest, dict) or not manifest:
        raise RuntimeError("Original asset manifest must be a nonempty object")
    for name, metadata in manifest.items():
        if (not name or name in (".", "..") or any(char in name for char in "/\\:")
                or not isinstance(metadata, dict) or not isinstance(metadata.get("sha256"), str)):
            raise RuntimeError(f"Invalid original asset manifest entry: {name}")
        source = staged / "assets" / name
        if not source.is_file():
            raise RuntimeError(f"Missing original asset: {name}")
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        if digest != metadata["sha256"]:
            raise RuntimeError(f"Original asset hash mismatch: {name}")
    if not (staged / "main.js").stat().st_size:
        raise RuntimeError("Scala.js main.js is empty")


def package(staged: Path, destination: Path, template: Path, *, root: Path, pages: bool = False) -> None:
    validate_destination(staged, destination, template, root=root)
    validate_assets(staged)
    html = render_template(template)
    destination = destination.resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    # Build on the destination filesystem so installation uses directory
    # renames. No existing package is moved until copying and validation finish.
    with tempfile.TemporaryDirectory(prefix=".whaley-web-", dir=destination.parent) as folder:
        candidate = Path(folder) / "bundle"
        copied = candidate / "assets"
        shutil.copytree(staged / "assets", copied)
        for source in staged.iterdir():
            if source.name == "assets":
                continue
            target = copied / source.name
            if target.exists():
                raise RuntimeError(f"Staged module and game asset paths overlap: {source.name}")
            # Preserve nested module chunks and their relative imports, not
            # only the current linker output's top-level main.js file.
            if source.is_dir():
                shutil.copytree(source, target)
            else:
                shutil.copy2(source, target)
        (candidate / "index.html").write_text(html, encoding="utf-8")
        (candidate / MARKER).write_text(MARKER_CONTENT, encoding="utf-8")
        if has_checkout_placeholder(destination):
            # Keep the versioned folder placeholder through each atomic rebuild.
            (candidate / CHECKOUT_PLACEHOLDER).touch()
        if pages:
            (candidate / ".nojekyll").touch()
        previous = Path(folder) / "previous"
        if destination.exists():
            destination.rename(previous)
        try:
            candidate.rename(destination)
        except OSError:
            if previous.exists():
                previous.rename(destination)
            raise


def run(args: Namespace, root: Path) -> int:
    from .sbt import launch

    scala = root / "Scala"
    staged = scala / "target" / "web"
    template = scala / "server" / "app" / "views" / "index.scala.html"
    destination = args.output if args.output is not None else (
        scala / "target" / "pages" if args.target == "pages" else root / "Apps" / "WhaleyWebBundle")
    # Reject unsafe destinations before the build replaces staged artifacts.
    validate_destination(staged, destination, template, root=root)
    if not args.skip_build:
        status = launch(root, ["web/stage"])
        if status:
            return status
    package(staged, destination, template, root=root, pages=args.target == "pages")
    print(f"Packaged static Scala.js bundle: {destination.resolve()}")
    return 0
